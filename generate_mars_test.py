"""
Generates a reproducible 1,000-move test sequence and expected 27-word counts
table for verifying MIPS update() in MARS against Python update().
"""
import os
import random

N_MOVES = 1000
DECAY_SHIFT = 3   # counts[i] -= counts[i] >> 3
INCREMENT = 16    # counts[3*ctx + move] += 16
SEED = 42


def counter(move):
    return (move + 1) % 3


def update(counts, ctx, move):
    for i in range(len(counts)):
        counts[i] -= counts[i] >> DECAY_SHIFT
    counts[3 * ctx + move] += INCREMENT


def predict(counts, ctx):
    row = counts[3 * ctx : 3 * ctx + 3]
    if max(row) == 0:
        return None
    return row.index(max(row))


def format_word_array(label, values, per_line=20):
    lines = [f"{label}:"]
    for i in range(0, len(values), per_line):
        chunk = ", ".join(str(v) for v in values[i : i + per_line])
        lines.append(f"    .word {chunk}")
    return "\n".join(lines)


def main():
    rng = random.Random(SEED)
    counts = [0] * 27
    test_ctx = []
    test_move = []

    # Simulate 1,001 rounds so we get 1,000 (ctx, move) training observations.
    # Mix biased and random play so all 9 contexts receive realistic updates.
    ctx = None
    for t in range(N_MOVES + 1):
        guess = predict(counts, ctx) if ctx is not None else None
        ai_move = rng.randrange(3) if guess is None else counter(guess)

        if t < 500:
            player_move = rng.choices([0, 1, 2], weights=[5, 3, 2])[0]
        else:
            player_move = rng.choices([0, 1, 2], weights=[2, 3, 5])[0]

        if ctx is not None:
            test_ctx.append(ctx)
            test_move.append(player_move)
            update(counts, ctx, player_move)

        ctx = 3 * player_move + ai_move

    os.makedirs("mips", exist_ok=True)
    out_path = os.path.join("mips", "test_data.asm")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("# Auto-generated by generate_mars_test.py (seed=42, 1000 moves)\n")
        f.write(".data\n")
        f.write(f"num_moves:\n    .word {len(test_ctx)}\n\n")
        f.write(format_word_array("test_ctx", test_ctx) + "\n\n")
        f.write(format_word_array("test_move", test_move) + "\n\n")
        f.write(format_word_array("expected_counts", counts, per_line=9) + "\n")

    print(f"Wrote {out_path} ({len(test_ctx)} moves).")
    print("Expected final 27-word counts table:")
    print(counts)


if __name__ == "__main__":
    main()
    